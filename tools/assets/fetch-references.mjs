#!/usr/bin/env node
// Downloads the candidate historical references in references/historical/manifest.json
// and writes references/historical/SOURCES.md with each image's source, date and rights.
//
//   node tools/assets/fetch-references.mjs            # fetch anything missing
//   node tools/assets/fetch-references.mjs --force    # re-fetch everything
//   node tools/assets/fetch-references.mjs --dry-run  # list what would be fetched
//
// loc.gov entries are resolved through the loc.gov JSON API (?fo=json). Rights come from the
// item's rights_advisory field; anything that isn't "No known restrictions" is flagged in
// SOURCES.md for review. Entries marked "manual" are listed but not downloaded.

import { mkdir, readFile, writeFile, access } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = join(ROOT, 'references', 'historical');
const MAX_WIDTH = 1024; // the loc.gov "v" derivative; keeps references/ small (plain git, no LFS)
const DELAY_MS = 1500; // loc.gov rate-limits bursts

const args = new Set(process.argv.slice(2));
const force = args.has('--force');
const dryRun = args.has('--dry-run');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const exists = (p) =>
  access(p).then(
    () => true,
    () => false,
  );

/** Picks the widest JPEG at or under maxWidth from a loc.gov image_url list ("url#h=..&w=.."). */
export function pickImage(imageUrls, maxWidth = MAX_WIDTH) {
  const candidates = imageUrls
    .map((u) => {
      const [url, frag = ''] = u.split('#');
      const w = Number(new URLSearchParams(frag).get('w')) || 0;
      return { url, w };
    })
    .filter((c) => /\.jpe?g$/i.test(c.url) && c.w > 0 && c.w <= maxWidth)
    .sort((a, b) => b.w - a.w);
  return candidates[0]?.url;
}

const first = (v) => (Array.isArray(v) ? v[0] : v);

async function fetchJson(url) {
  const u = new URL(url);
  u.searchParams.set('fo', 'json');
  const res = await fetch(u, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`${res.status} for ${u}`);
  return res.json();
}

async function resolveLoc(source) {
  const json = await fetchJson(source);
  const item = json.item ?? {};
  const imageUrls = json.image_url ?? item.image_url ?? [];
  // Resource pages list files under page[].url without size hints; the "v" JPEG is ~1024 px.
  const pageV = (json.page ?? []).map((p) => p.url).find((u) => /v\.jpg$/.test(u ?? ''));
  return {
    title: first(item.title) ?? json.title ?? '',
    date: first(item.created_published_date) ?? first(item.date) ?? json.date ?? '',
    rights: first(item.rights_advisory) ?? first(json.rights_advisory) ?? '',
    repro: first(item.reproduction_number) ?? '',
    image: pickImage(imageUrls) ?? pageV,
  };
}

async function main() {
  const manifest = JSON.parse(await readFile(join(DIR, 'manifest.json'), 'utf8'));
  const rows = [];
  for (const entry of manifest.entries) {
    const out = join(DIR, `${entry.file}.jpg`);
    const row = { ...entry, path: `${entry.file}.jpg`, status: '' };
    rows.push(row);
    if (entry.manual) {
      row.status = 'manual download';
      continue;
    }
    if (!entry.source.includes('loc.gov')) {
      row.status = 'unsupported host';
      continue;
    }
    try {
      Object.assign(row, await resolveLoc(entry.source));
      if (!row.image) throw new Error('no JPEG under max width');
      if (dryRun) {
        row.status = 'dry run';
      } else if (!force && (await exists(out))) {
        row.status = 'ok (kept)';
      } else {
        const res = await fetch(row.image);
        if (!res.ok) throw new Error(`${res.status} for ${row.image}`);
        await mkdir(dirname(out), { recursive: true });
        await writeFile(out, Buffer.from(await res.arrayBuffer()));
        row.status = 'ok';
      }
    } catch (err) {
      row.status = `failed: ${err.message}`;
    }
    console.log(`${row.status.padEnd(12)} ${row.path}`);
    await sleep(DELAY_MS);
  }
  if (!dryRun) await writeFile(join(DIR, 'SOURCES.md'), renderSources(rows));
}

function renderSources(rows) {
  const esc = (s) =>
    String(s ?? '')
      .replace(/\|/g, '\\|')
      .replace(/\s+/g, ' ')
      .trim();
  const lines = [
    '# Historical reference sources',
    '',
    'Generated by `tools/assets/fetch-references.mjs` from `manifest.json`. Do not edit by hand.',
    '',
    'These are look-and-feel references, not shipped assets. Rights are copied from each',
    "item's record. A ⚠ marks a rights statement that needs a closer look before reuse.",
    '',
    '| Image | Title | Date | Source | Rights | Why | Status |',
    '| ----- | ----- | ---- | ------ | ------ | --- | ------ |',
  ];
  for (const r of rows) {
    const rights = r.license ?? r.rights ?? '';
    const flag = rights && !/no known restrictions|public domain/i.test(rights) ? '⚠ ' : '';
    const src = r.repro ? `[${esc(r.repro)}](${r.source})` : `[link](${r.source})`;
    lines.push(
      `| ${r.status.startsWith('ok') ? `[${r.path}](${r.path})` : r.path} | ${esc(r.title)} | ${esc(r.date)} | ${src} | ${flag}${esc(rights)} | ${esc(r.why)} | ${esc(r.status)} |`,
    );
  }
  return lines.join('\n') + '\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
